# -*- coding: utf-8 -*-
"""Глушение источников колокольчика для юнит-тестов без Postgres.

Колокольчик собирается из НЕСКОЛЬКИХ таблиц, и список растёт: входящие запросы доступа, ответ
на свой запрос, «ваша проблема решена». Каждый новый источник ломал разом все тесты, которые
ходят в `/attention`, — и в трёх местах приходилось дописывать одну и ту же заглушку.

Здесь она одна. Тест, которому нужен КОНКРЕТНЫЙ источник, глушит всё этим хелпером, а затем
подменяет нужную функцию своей — порядок вызовов monkeypatch это позволяет.
"""


def silence_db_sources(monkeypatch, main):
    """Все походы `/attention` в базу отвечают пусто."""

    async def _none(*a, **kw):
        return []

    for name in ("fetch_access_requests", "fetch_problems_by_reporter", "fetch_project_rows_by_ids"):
        monkeypatch.setattr(main.db, name, _none)

/* ─────────────────────────────────────────────────────────────────────────────
 * Новости портала — тот же случай, что и справка: это КОНТЕНТ, а не подписи
 * интерфейса, поэтому он живёт здесь, а не в локалях. См. пояснение в
 * src/content/wiki/types.ts — причины ровно те же.
 *
 * ПРАВИЛО: каждое изменение портала, заметное пользователю, сопровождается новостью.
 * Пишется она тем же изменением, что и сама правка, сразу на трёх языках. Русский —
 * язык-источник: состав и порядок новостей берётся из него, переводится только текст.
 * Паритет стережёт news.test.ts.
 *
 * Блоки переиспользуются из справки намеренно: один тип — один рендерер, одна
 * проверенная вёрстка в светлой и тёмной теме, и ни одного нового способа
 * вставить в страницу произвольный HTML.
 * ───────────────────────────────────────────────────────────────────────────── */
import type { WikiBlock } from '../wiki/types'

export interface NewsItem {
  /** Стабильный ключ. По нему сверяется паритет языков; в адресах не участвует. */
  id: string
  /** YYYY-MM-DD. По ней сортировка и отметка «новое». Не локализуется. */
  date: string
  title: string
  /** Одна строка для списка: что изменилось, простым языком и без терминов. */
  summary: string
  blocks: WikiBlock[]
}
